package com.levelchef.data.recipe

import com.levelchef.core.model.Recipe
import com.levelchef.core.model.RecipeIngredient
import com.levelchef.core.model.RecipeStep

private const val MIN_XP = 10
private const val MAX_XP = 200
private const val MAX_TIME_MINUTES = 600
private const val MAX_SERVINGS = 12
private const val MAX_MACRO = 5000
private const val MAX_TIMER_MINUTES = 240
private const val MAX_QUANTITY = 100_000.0
private const val MAX_LIST_SIZE = 30
private const val MAX_TAGS = 3
private const val MAX_TEXT = 500
private const val MAX_EMOJI_CHARS = 16
private const val DEFAULT_EMOJI = "🍽️"

/**
 * Turns a recipe as generated by Gemini into one the app can trust. Gemini's output is
 * schema-shaped but otherwise unchecked, so:
 * - the id is replaced by an app-generated [newId] — a model-chosen slug repeats across batches
 *   ("lemon-garlic-chicken" again next week), which would overwrite a saved/cooked recipe in the
 *   `generatedRecipe` table, and could contain characters that break a navigation route;
 * - numbers are clamped to sane ranges (XP drives the level system, servings divides quantities);
 * - the video link is never taken from the model: it's rebuilt as a YouTube search for the name.
 * Returns null when there's nothing usable (blank name or no steps).
 */
internal fun Recipe.sanitized(newId: String): Recipe? {
    val cleanName = name.trim().take(MAX_TEXT)
    val cleanSteps = steps.mapNotNull { it.sanitized() }.take(MAX_LIST_SIZE)
    if (cleanName.isEmpty() || cleanSteps.isEmpty()) return null
    return copy(
        id = newId,
        name = cleanName,
        emoji = emoji.trim().takeIf { it.isNotEmpty() && it.length <= MAX_EMOJI_CHARS } ?: DEFAULT_EMOJI,
        xpReward = xpReward.coerceIn(MIN_XP, MAX_XP),
        timeMinutes = timeMinutes.coerceIn(1, MAX_TIME_MINUTES),
        servings = servings.coerceIn(1, MAX_SERVINGS),
        caloriesKcal = caloriesKcal?.takeIf { it in 0..MAX_MACRO },
        proteinGrams = proteinGrams?.takeIf { it in 0..MAX_MACRO },
        carbsGrams = carbsGrams?.takeIf { it in 0..MAX_MACRO },
        fatGrams = fatGrams?.takeIf { it in 0..MAX_MACRO },
        tags = tags.map { it.trim().take(MAX_TEXT) }.filter { it.isNotEmpty() }.take(MAX_TAGS),
        ingredients = ingredients.mapNotNull { it.sanitized() }.take(MAX_LIST_SIZE),
        steps = cleanSteps,
        videoUrl = youtubeSearchUrl(cleanName),
    )
}

private fun RecipeIngredient.sanitized(): RecipeIngredient? {
    val cleanName = name.trim().take(MAX_TEXT)
    if (cleanName.isEmpty()) return null
    val cleanQuantity = quantity?.takeIf { it.isFinite() && it > 0.0 && it <= MAX_QUANTITY }
    return copy(
        name = cleanName,
        quantity = cleanQuantity,
        unit = unit?.trim()?.take(MAX_TEXT)?.takeIf { it.isNotEmpty() && cleanQuantity != null },
    )
}

private fun RecipeStep.sanitized(): RecipeStep? {
    val cleanText = text.trim().take(MAX_TEXT)
    if (cleanText.isEmpty()) return null
    return copy(text = cleanText, timerMinutes = timerMinutes?.takeIf { it in 1..MAX_TIMER_MINUTES })
}

/** A YouTube search URL for [query], percent-encoded as `application/x-www-form-urlencoded`. */
internal fun youtubeSearchUrl(query: String): String =
    "https://www.youtube.com/results?search_query=" + formEncode(query)

private fun formEncode(value: String): String = buildString {
    value.encodeToByteArray().forEach { byte ->
        val c = byte.toInt().toChar()
        when {
            c in 'a'..'z' || c in 'A'..'Z' || c in '0'..'9' || c in "-_.*" -> append(c)
            c == ' ' -> append('+')
            else -> append('%').append(HEX[(byte.toInt() shr 4) and 0xF]).append(HEX[byte.toInt() and 0xF])
        }
    }
}

private const val HEX = "0123456789ABCDEF"
